'use strict';

const helmet = require('helmet');

function createHelmetMiddleware() {
  return helmet({
    // This build is served exclusively over loopback HTTP, including fonts.
    strictTransportSecurity: false,
    contentSecurityPolicy: {
      directives: {
        defaultSrc: ["'self'"],
        scriptSrc: ["'self'"],
        styleSrc: ["'self'", "'unsafe-inline'"],
        imgSrc: ["'self'", 'data:'],
        connectSrc: ["'self'"],
        fontSrc: ["'self'"],
        upgradeInsecureRequests: null,
        frameSrc: ["'self'", 'blob:'],
        objectSrc: ["'none'"],
        baseUri: ["'self'"],
        formAction: ["'self'"],
        frameAncestors: ["'none'"]
      }
    }
  });
}

module.exports = { createHelmetMiddleware };

