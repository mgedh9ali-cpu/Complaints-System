'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const {SOURCE_FILES,assembleUiBundle,validateUiBundle}=require('../lib/ui-bundle');
const root=path.resolve(__dirname,'..');
test('modular UI is assembled in declared order with valid JavaScript',()=>{
 assert.ok(SOURCE_FILES.length>=10);
 const result=validateUiBundle(root);
 assert.ok(result.size>40000);
 const content=assembleUiBundle(root);
 assert.doesNotThrow(()=>new vm.Script(content));
 assert.match(content,/function render\(/);
 assert.match(content,/api\('\/api\/state'/);
 assert.match(content,/function detailModal\(/);
 for(const file of SOURCE_FILES)assert.ok(fs.statSync(path.join(root,file)).size>10);
 assert.equal(fs.existsSync(path.join(root,'app.full.js')),false,'remove monolithic file');
 const loader=fs.readFileSync(path.join(root,'app.js'),'utf8');
 assert.match(loader,/script.src = '\/app.bundle.js'/);
 assert.doesNotMatch(loader,/eval\(/);
 const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
 assert.match(server,/app\.get\('\/app\.bundle\.js'/);
 assert.match(server,/assembleUiBundle/);
});
